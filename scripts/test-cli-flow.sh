mock_validator_id() { # mock_validator_id <name>
  mock_validators | NAME="$1" node -e '
    let s = "";
    process.stdin.on("data", (d) => (s += d)).on("end", () => {
      const v = JSON.parse(s).validators.find((v) => v.name === process.env.NAME);
      console.log(v ? v.id : "");
    });'
}

