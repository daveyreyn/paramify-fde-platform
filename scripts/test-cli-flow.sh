# check <description> <want_exit> <pattern> <runner...>
#   want_exit: 0 | fail | an exact code (e.g. 3)
#   pattern:   extended regex the output must match; prefix with ! to require
#              absence; "" to skip the output assertion
check() {
  local desc=$1 want_exit=$2 pattern=$3
  shift 3
  N=$((N + 1))

  local out code
  out=$("$@" 2>&1)
  code=$?

  log ""
  log "### $N. $desc"
  log '```'
  log "\$ $*"
  log "$out"
  log '```'

  local problems=""
  case "$want_exit" in
    0) [ $code -eq 0 ] || problems="expected success, exited $code" ;;
    fail) [ $code -ne 0 ] || problems="expected failure, exited 0" ;;
    *) [ $code -eq "$want_exit" ] || problems="expected exit $want_exit, got $code" ;;
  esac
  if [ -n "$pattern" ]; then
    case "$pattern" in
      !*)
        if printf '%s' "$out" | grep -qE -- "${pattern#!}"; then
          problems="${problems:+$problems; }output unexpectedly matched '${pattern#!}'"
        fi
        ;;
      *)
        if ! printf '%s' "$out" | grep -qE -- "$pattern"; then
          problems="${problems:+$problems; }output did not match '$pattern'"
        fi
        ;;
    esac
  fi

  if [ -z "$problems" ]; then
    PASS=$((PASS + 1))
    log "exit: $code — ok"
    printf '  ok   %2d. %s\n' "$N" "$desc"
  else
    FAIL=$((FAIL + 1))
    log "exit: $code — **FAILED: $problems**"
    printf 'FAIL   %2d. %s (%s)\n' "$N" "$desc" "$problems"
  fi
}

mint_token() { # mint_token <email> — insert an ApiToken directly, print it
  EMAIL="$1" DATABASE_URL="$DB_URL" node --input-type=module <<'EOF'
import { getPrisma } from './packages/db/dist/index.js';
import { generateToken, hashToken } from './packages/shared/dist/token.js';
const prisma = getPrisma();
const user = await prisma.user.findUnique({ where: { email: process.env.EMAIL } });
if (!user) {
  console.error(`no such user: ${process.env.EMAIL}`);
  process.exit(1);
}
const token = generateToken();
await prisma.apiToken.create({
  data: { tokenHash: hashToken(token), label: 'cli', userId: user.id },
});
console.log(token);
await prisma.$disconnect();
EOF
}

blob_count() { ls "$STORAGE" 2>/dev/null | wc -l | tr -d ' '; }

