# scratch storage dir — your dev server and dev.db are untouched), then runs
# every CLI command as two identities (a super user and a regular member),
# asserting the happy path and the failure invariants of each. Every command
# and its output is appended to a markdown transcript so the whole flow can
# be read top to bottom.
#
# Usage:
#   scripts/test-cli-flow.sh [transcript-path]   # default: cli-flow-transcript.md
#   SKIP_BUILD=1 scripts/test-cli-flow.sh        # reuse the existing build
#
# Exits non-zero if any check fails.

