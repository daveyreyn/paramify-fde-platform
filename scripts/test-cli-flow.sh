import { randomUUID } from 'node:crypto';
import { createServer } from 'node:http';

const KEY = process.env.MOCK_PARAMIFY_KEY;
const validators = new Map();

const send = (res, status, body) => {
  res.writeHead(status, { 'content-type': 'application/json' });
  res.end(body === undefined ? '' : JSON.stringify(body));
};

createServer(async (req, res) => {
  const url = new URL(req.url, 'http://mock');
  if (url.pathname === '/healthz') return send(res, 200, { ok: true });
  if (req.headers.authorization !== `Bearer ${KEY}`) {
    return send(res, 401, { message: 'The credentials used are invalid.' });
  }
  const match = url.pathname.match(/^\/api\/v0\/validators(?:\/([^/]+))?$/);
  if (!match) return send(res, 404, { message: 'Not found.' });
  const id = match[1];
  let raw = '';
  for await (const chunk of req) raw += chunk;
  const body = raw ? JSON.parse(raw) : {};

  if (!id && req.method === 'GET') {
    return send(res, 200, { validators: [...validators.values()] });
  }
  if (!id && req.method === 'POST') {
    if ([...validators.values()].some((v) => v.name === body.name)) {
      return send(res, 400, { message: 'A validator with this name already exists.' });
    }
    const validator = {
      id: randomUUID(),
      name: body.name,
      statement: body.statement,
      type: body.type,
      regex: body.regex ?? '',
      validationRules: body.validationRules ?? [],
    };
    validators.set(validator.id, validator);
    return send(res, 200, validator);
  }
  const existing = id && validators.get(id);
  if (!existing) return send(res, 404, { message: 'Validator not found.' });
  if (req.method === 'GET') return send(res, 200, existing);
  if (req.method === 'PATCH') return send(res, 200, Object.assign(existing, body));
  if (req.method === 'DELETE') {
    validators.delete(id);
    return send(res, 200, undefined);
  }
  return send(res, 405, { message: 'Method not allowed.' });
}).listen(Number(process.env.MOCK_PARAMIFY_PORT), '127.0.0.1');
EOF
MOCK_PARAMIFY_KEY="$MOCK_PARAMIFY_KEY" MOCK_PARAMIFY_PORT="$MOCK_PARAMIFY_PORT" \
